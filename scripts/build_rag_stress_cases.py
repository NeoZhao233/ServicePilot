def build() -> list[dict[str, object]]:
    if hashlib.sha256(POLICIES.read_bytes()).hexdigest() != EXPECTED_SHA256:
        raise ValueError("Policy corpus changed: review labels before regenerating")
    policies = json.loads(POLICIES.read_text(encoding="utf-8"))
    groups = (("single", SINGLE), ("pair", PAIR), ("triple", TRIPLE), ("quad", QUAD))
    output = []
    for group, rows in groups:
        for number, (query, labels) in enumerate(rows, 1):
            output.append(
                {
                    "case_id": f"stress_{group}_{number:02d}",
                    "query": query,
                    "relevant_policy_ids": [policies[index]["policy_id"] for index in labels],
                    "slice": group,
                    "difficulty": "hard" if group != "single" else "medium",
                    "source": "synthetic_handwritten",
                }
            )
    if len(output) != 100 or len({case["query"] for case in output}) != 100:
        raise ValueError("Expected 100 unique questions")
    return output


if __name__ == "__main__":
    path = ROOT / "evaluations/rag_stress_cases.json"
    path.write_text(json.dumps(build(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(path)
